/**
 * Every generated ABI gets a module of its own under `src/generated/abi/`,
 * re-exported from `juicebox.ts`.
 *
 * A bundler keeps every export of a module that any chunk uses, in the chunk
 * that loads the module, and some bundlers cannot drop an unused declaration
 * from a module they wrap. In a module of its own, an ABI loads only with the
 * chunks that import it.
 */
const HEADER = `// Generated by scripts/addJBProjectDeploymentAddresses.ts. Do not edit.
// Each ABI has a module of its own, so a page loads only the ABIs it imports.
`;

/** The ABIs `source` declares, in the order it declares them. */
export function declaredAbis(source: string): string[] {
  return [...source.matchAll(/^export const (\w+Abi) = \[/gm)].map(
    ([, name]) => name,
  );
}

/**
 * Move each named `export const <name> = [...] as const` out of the generated
 * source into a module of its own, leaving a re-export in its place, and point
 * any alias of it (`export { <name> as <alias> }`) at that module. Throws when a
 * name is missing, so a renamed contract cannot silently drop out.
 */
export function splitAbiModules(
  source: string,
  names: readonly string[] = declaredAbis(source),
): { source: string; modules: Record<string, string> } {
  const modules: Record<string, string> = {};
  let rest = source;
  for (const name of names) {
    const declaration = new RegExp(
      `^export const ${name} = \\[[\\s\\S]*?^\\] as const;?$`,
      "m",
    );
    const match = rest.match(declaration);
    if (!match) throw new Error(`The generated bindings have no ${name}.`);
    modules[name] = `${HEADER}\n${match[0]}\n`;
    rest = rest
      .replace(declaration, `export { ${name} } from './abi/${name}.js'`)
      .replace(
        new RegExp(`^export \\{ ${name} as (\\w+) \\}$`, "gm"),
        `export { ${name} as $1 } from './abi/${name}.js'`,
      );
  }
  return { source: rest, modules };
}
