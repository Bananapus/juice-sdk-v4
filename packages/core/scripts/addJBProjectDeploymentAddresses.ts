import {
  Contract,
  JBChainId,
  JBVersion,
  SUPPORTED_CHAINS,
} from "../src/contracts.js";
import fs from "fs";
import { format } from "prettier";
import { resolve } from "node:path";
import { aliasRouterAbis } from "./aliasRouterAbis.js";
import { splitAbiModules } from "./splitAbiModules.js";
import {
  deploymentFilePath,
  getAllContractNames,
  getHistoricalContract,
  isMissingDeployment,
  V6_HISTORY,
  getContractAddress,
  getV6CcipDeployerAddress,
  getV6NativeDeployerAddress,
} from "./utils.js";

const chainIds = Object.keys(SUPPORTED_CHAINS).map(Number) as JBChainId[];

const MAINNET_CHAIN_IDS: JBChainId[] = [1, 10, 8453, 42161];

async function buildAddressesFor(version: JBVersion) {
  const addresses = {};

  const names = getAllContractNames(version);

  for (const name of names) {
    addresses[name] = {};
    for (const chainId of chainIds) {
      try {
        addresses[name][chainId] = await getContractAddress(
          name,
          version,
          chainId,
        );
      } catch (e) {
        // Not every v6 contract is deployed on every chain (e.g. the v6 JBBuybackHook is not
        // on optimism_sepolia). A missing v4/v5 artifact is a regression — fail loudly.
        if (version !== 6 || !isMissingDeployment(e)) throw e;
        console.warn(
          `No v${version} ${name} deployment on chain ${chainId}, skipping.`,
        );
      }
    }
  }

  return addresses;
}

/**
 * v6 CCIP sucker deployer addresses, keyed by local chain then remote chain.
 */
async function buildV6CcipDeployerAddresses() {
  const addresses = {};

  for (const chainId of chainIds) {
    const isMainnet = MAINNET_CHAIN_IDS.includes(chainId);
    const peers = chainIds.filter(
      (peer) =>
        peer !== chainId && MAINNET_CHAIN_IDS.includes(peer) === isMainnet,
    );

    addresses[chainId] = {};
    for (const peer of peers) {
      addresses[chainId][peer] = await getV6CcipDeployerAddress(chainId, peer);
    }
  }

  return addresses;
}

/**
 * v6 native-bridge sucker deployer addresses, keyed by local chain then remote chain.
 * Only L1<->L2 edges exist (native bridges only connect Ethereum with an L2).
 */
async function buildV6NativeDeployerAddresses() {
  const addresses = {};

  for (const chainId of chainIds) {
    const isMainnet = MAINNET_CHAIN_IDS.includes(chainId);
    const peers = chainIds.filter(
      (peer) =>
        peer !== chainId && MAINNET_CHAIN_IDS.includes(peer) === isMainnet,
    );

    addresses[chainId] = {};
    for (const peer of peers) {
      const address = await getV6NativeDeployerAddress(chainId, peer);
      if (address) addresses[chainId][peer] = address;
    }
  }

  return addresses;
}

async function buildV6History() {
  const history = {};
  for (const name of Object.keys(V6_HISTORY) as Contract[]) {
    history[name] = {};
    for (const generation of ["previous", "v1"] as const) {
      history[name][generation] = {};
      for (const chainId of chainIds) {
        try {
          history[name][generation][chainId] = (
            await getHistoricalContract(name, generation, chainId)
          ).address;
        } catch (error) {
          if (!isMissingDeployment(error)) throw error;
        }
      }
    }
  }
  return history;
}

const ADDRESS_MODULE_HEADER = `// Generated by scripts/addJBProjectDeploymentAddresses.ts. Do not edit.
// One deployment table per version, so a page loads only the version it reads.
`;

/**
 * The deployment tables. Each version's table is a module of its own under
 * `src/generated/addresses/`; `jbContractAddress` joins the three, keyed by
 * version, in a module of its own as well.
 */
async function buildAddressModules(): Promise<Record<string, string>> {
  const modules: Record<string, string> = {};
  for (const version of [4, 5, 6] as const) {
    const name = `jbV${version}ContractAddress`;
    const table = await buildAddressesFor(version);
    modules[name] = `${ADDRESS_MODULE_HEADER}
/**
 * Juicebox V${version} deployment addresses, keyed by contract, then chain.
 */
export const ${name} = ${JSON.stringify(table, null, 2)} as const;
`;
  }
  modules.jbContractAddress = `${ADDRESS_MODULE_HEADER}
import { jbV4ContractAddress } from './jbV4ContractAddress.js'
import { jbV5ContractAddress } from './jbV5ContractAddress.js'
import { jbV6ContractAddress } from './jbV6ContractAddress.js'

/**
 * Addresses to use in JB project deployments, keyed by version. Prefer the
 * version's own table (\`jbV6ContractAddress\`): this one loads all three.
 */
export const jbContractAddress = {
  "4": jbV4ContractAddress,
  "5": jbV5ContractAddress,
  "6": jbV6ContractAddress,
} as const;
`;
  return modules;
}

async function buildDefaultAddressContent() {
  const current = await buildAddressesFor(6);
  const history = await buildV6History();
  const generations = {};
  for (const name of Object.keys(V6_HISTORY)) {
    generations[name] = {};
    for (const [chainId, address] of Object.entries(current[name])) {
      generations[name][chainId] =
        ["previous", "v1"].find(
          (generation) =>
            history[name][generation][chainId]?.toLowerCase() ===
            (address as string).toLowerCase(),
        ) ?? "current";
    }
  }
  const content = `
export { jbContractAddress } from './addresses/jbContractAddress.js'
export { jbV4ContractAddress } from './addresses/jbV4ContractAddress.js'
export { jbV5ContractAddress } from './addresses/jbV5ContractAddress.js'
export { jbV6ContractAddress } from './addresses/jbV6ContractAddress.js'

  /**
   * v6 CCIP sucker deployer addresses, keyed by local chain then remote chain.
   */
  export const jbCcipSuckerDeployerAddress = ${JSON.stringify(
    {
      6: await buildV6CcipDeployerAddresses(),
    },
    null,
    2,
  )} as const;

  /**
   * v6 native-bridge sucker deployer addresses, keyed by local chain then remote chain.
   * Native bridges only connect Ethereum with an L2, so only L1<->L2 edges exist.
   */
  export const jbNativeSuckerDeployerAddress = ${JSON.stringify(
    {
      6: await buildV6NativeDeployerAddresses(),
    },
    null,
    2,
  )} as const;

  /** Historical v6 deployments retained for activity decoding and projects that have not migrated. */
  export const jbContractAddressHistory = ${JSON.stringify({ 6: history }, null, 2)} as const;

  /** ABI generation for each canonical v6 deployment during the phased rollout. */
  export const jbContractAbiGeneration = ${JSON.stringify({ 6: generations }, null, 2)} as const;`;
  return content;
}

/** Write `dir` to hold exactly `modules`, removing any module no longer generated. */
function writeModules(dir: string, modules: Record<string, string>) {
  fs.mkdirSync(dir, { recursive: true });
  for (const file of fs.readdirSync(dir)) {
    if (!Object.hasOwn(modules, file.replace(/\.ts$/, "")))
      fs.rmSync(`${dir}/${file}`);
  }
  for (const [name, module] of Object.entries(modules)) {
    fs.writeFileSync(`${dir}/${name}.ts`, module);
  }
}

async function addDefaultAddresses() {
  const filePath = "src/generated/juicebox.ts";
  const content = await buildDefaultAddressContent();
  const addressModules = await buildAddressModules();
  const bindings = splitAbiModules(
    aliasRouterAbis(fs.readFileSync(filePath, "utf8")),
  );
  if (!Object.keys(bindings.modules).length)
    throw new Error(
      `${filePath} declares no ABIs: run wagmi generate (npm run generate) first.`,
    );
  writeModules("src/generated/abi", bindings.modules);
  writeModules("src/generated/addresses", addressModules);
  fs.writeFileSync(filePath, bindings.source + content);
  // Sticky owns receipt and constructor validation. Consume its checked export,
  // rather than teaching SDK generation a second artifact format.
  const stickyArtifact = deploymentFilePath(
    "@bananapus/sticky-v6/deployments/ethereum/StickyHook.json",
  );
  const collectors = JSON.parse(
    fs.readFileSync(
      resolve(
        stickyArtifact,
        "../../../web/src/lib/sticky-source-collectors.json",
      ),
      "utf8",
    ),
  );
  if (!Array.isArray(collectors))
    throw new Error("Invalid Sticky collector export");
  fs.writeFileSync(
    "src/generated/stickySourceCollectors.ts",
    await format(
      `// Generated from the pinned Sticky verified deployment export. Do not edit.\nexport const stickySourceCollectorDeployments = ${JSON.stringify(collectors, null, 2)} as const;\n`,
      { parser: "typescript" },
    ),
  );
}

addDefaultAddresses();
